// Generates `app/theme-tokens.css` from `lib/theme/shadcn-data.json`.
//
// Selector order (equal specificity, later wins):
//   1. [data-base="X"][data-mode="Y"]   — full token set
//   2. [data-accent="X"][data-mode="Y"] — 11 override keys
//   3. [data-chart="X"][data-mode="Y"]  — chart-1..5
//
// "default" accent and "default" chart generate NO rules:
//   - accent="default": nothing overrides the base
//   - chart="default": the accent's chart-1..5 (or the base's) wins

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_PATH = resolve(__dirname, "../lib/theme/shadcn-data.json");
const OUT_PATH = resolve(__dirname, "../app/theme-tokens.css");

/** Format a CSS variable declaration. */
function decl(name, value) {
  return `    ${name}: ${value};`;
}

function baseBlock(name, mode, tokens) {
  const lines = Object.entries(tokens)
    // Skip the `radius` field — radius is a layout token, not a color, and the
    // user dropped the radius slider. Leave it in the data for reference, but
    // don't emit it as a CSS variable.
    .filter(([k]) => k !== "radius")
    .map(([k, v]) => decl(`--${k}`, v));
  return `[data-base="${name}"][data-mode="${mode}"] {\n${lines.join("\n")}\n}`;
}

function accentBlock(name, mode, tokens) {
  const lines = Object.entries(tokens).map(([k, v]) => decl(`--${k}`, v));
  return `[data-accent="${name}"][data-mode="${mode}"] {\n${lines.join("\n")}\n}`;
}

function chartBlock(name, mode, accentTokens) {
  // The chart override is just chart-1..5, taken from the matching accent.
  const chartLines = [];
  for (let i = 1; i <= 5; i++) {
    const k = `chart-${i}`;
    if (accentTokens[k]) chartLines.push(decl(`--${k}`, accentTokens[k]));
  }
  return `[data-chart="${name}"][data-mode="${mode}"] {\n${chartLines.join("\n")}\n}`;
}

async function main() {
  const data = JSON.parse(await readFile(DATA_PATH, "utf8"));

  const blocks = [];
  let baseCount = 0;
  let accentCount = 0;
  let chartCount = 0;

  // 1. Base blocks (full set, light + dark per base).
  for (const [name, theme] of Object.entries(data.bases)) {
    blocks.push(baseBlock(name, "light", theme.light));
    blocks.push(baseBlock(name, "dark", theme.dark));
    baseCount += 2;
  }

  // 2. Accent blocks (11 overrides, light + dark per non-default accent).
  for (const [name, theme] of Object.entries(data.accents)) {
    if (!theme) continue; // "default" — skip
    blocks.push(accentBlock(name, "light", theme.light));
    blocks.push(accentBlock(name, "dark", theme.dark));
    accentCount += 2;
  }

  // 3. Chart blocks (chart-1..5 only). The chart-1..5 values come from the
  // matching accent's tokens (which is also what /create uses).
  for (const [name, theme] of Object.entries(data.accents)) {
    if (!theme) continue; // "default" — skip
    blocks.push(chartBlock(name, "light", theme.light));
    blocks.push(chartBlock(name, "dark", theme.dark));
    chartCount += 2;
  }

  // Header.
  const header = `/* AUTO-GENERATED by scripts/generate-theme-css.mjs
 * Source: lib/theme/shadcn-data.json (rebuilt by scripts/fetch-shadcn-data.mjs)
 * DO NOT EDIT. Regenerate with:
 *   node scripts/fetch-shadcn-data.mjs && node scripts/generate-theme-css.mjs
 *
 * Selector cascade (equal specificity, later wins):
 *   [data-base]   sets every color token
 *   [data-accent] overrides 11 primary-related keys
 *   [data-chart]  overrides chart-1..5
 */
`;

  const out = header + blocks.join("\n\n") + "\n";
  await writeFile(OUT_PATH, out);

  // Sanity counts. Match the math in plans/2026-10-16_2155-shadcn-theme-editor.md.
// Each base block emits (full token count minus `radius`) declarations × 2 modes.
// Each accent block emits ACCENT_KEYS.length declarations × 2 modes.
// Each chart block emits chart-1..5 (5 keys) × 2 modes.
  const firstBase = Object.values(data.bases)[0];
  const tokensPerBaseMode = Math.max(0, Object.keys(firstBase.light).length - 1); // minus radius
  // ACCENT_KEYS lives in fetch-shadcn-data.mjs; the count here is a derived sanity check.
  const sampleAccent = Object.values(data.accents).find((a) => a);
  const accentKeys = sampleAccent ? Object.keys(sampleAccent.light).length : 0;
  const baseRows = baseCount * tokensPerBaseMode;
  const accentRows = accentCount * accentKeys;
  const chartRows = chartCount * 5; // chart-1..5
  const totalTokenRows = baseRows + accentRows + chartRows;

  console.log(`→ Wrote ${OUT_PATH}`);
  console.log(`  base selectors:   ${baseCount} (${baseCount / 2} bases × 2 modes)`);
  console.log(`  accent selectors: ${accentCount} (24 accents × 2 modes)`);
  console.log(`  chart selectors:  ${chartCount} (24 charts × 2 modes)`);
  console.log(`  total selectors:  ${baseCount + accentCount + chartCount}`);
  console.log(`  tokens per base block: ${tokensPerBaseMode} (32 - radius)`);
  console.log(`  keys per accent block: ${accentKeys} (mirror of ACCENT_KEYS in fetch-shadcn-data.mjs)`);
  console.log(`  base rows:   ${baseRows} (${baseCount} × ${tokensPerBaseMode})`);
  console.log(`  accent rows: ${accentRows} (${accentCount} × ${accentKeys})`);
  console.log(`  chart rows:  ${chartRows} (${chartCount} × 5 chart keys)`);
  console.log(`  total rows:  ${totalTokenRows}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
